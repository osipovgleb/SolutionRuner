"""Complete square-root questions, including explicit source and answer units."""

import re

_ACCELERATION = r"(?P<acceleration_unit>км/ч|м/с)\^\{2\}"
_TARGET_SPEED = r"(?P<speed>.+?) (?P<speed_unit>км/ч|м/с)"
_FORMULA = r"(?P<formula>.+?)"
PATTERNS = (
    (
        "root_acceleration",
        re.compile(
            r"(?:Гоночный автомобиль|Автомобиль) разгоняется на прямолинейном участке шоссе с постоянным ускорением a "
            + _ACCELERATION
            + r"\. Скорость(?: v в конце пути)? вычисляется по формуле v="
            + _FORMULA
            + r", где l — пройденный автомобилем путь(?P<formal_path_unit> в км)?\. (?:Найдите|Определите) ускорение, с которым должен двигаться автомобиль, чтобы, проехав (?P<path>.+?) (?P<path_unit>километр|километра|метров), приобрести скорость "
            + _TARGET_SPEED
            + r"\. Ответ выразите в (?P<answer_unit>км/ч|м/с)\^\{2\}\."
        ),
    ),
    (
        "root_acceleration_min",
        re.compile(
            r"Скорость автомобиля, разгоняющегося с места старта по прямолинейному отрезку пути длиной l км с постоянным ускорением a "
            + _ACCELERATION
            + r", вычисляется по формуле v="
            + _FORMULA
            + r"\. Определите наименьшее ускорение, с которым должен двигаться автомобиль, чтобы, проехав (?P<path>.+?) (?P<path_unit>километр|километра|метров), приобрести скорость не менее "
            + _TARGET_SPEED
            + r"\. Ответ выразите в (?P<answer_unit>км/ч|м/с)\^\{2\}\."
        ),
    ),
    (
        "root_distance",
        re.compile(
            r"Автомобиль разгоняется на прямолинейном участке шоссе с постоянным ускорением a=(?P<acceleration>.+?) "
            + _ACCELERATION
            + r"\. Скорость(?: v(?:\(в (?P<declared_speed_unit>км/ч)\))?)?\s*вычисляется по формуле v="
            + _FORMULA
            + r",? где l — пройденный автомобилем путь(?P<path_unit> в км| в м|\(в км\))?\. Найдите, сколько (?P<answer_unit>километров|метров) проедет автомобиль к моменту, когда он разгонится до скорости "
            + _TARGET_SPEED
            + r"\."
        ),
    ),
    (
        "rocket",
        re.compile(
            r"При движении ракеты ее видимая для неподвижного наблюдателя длина, измеряемая в метрах, сокращается по закону l="
            + _FORMULA
            + r", где l_0=(?P<length>.+?) м — длина покоящейся ракеты, c=(?P<light>.+?) км/с — скорость света, а v — скорость ракеты\(в км/с\)\. Какова должна быть минимальная скорость ракеты, чтобы ее наблюдаемая длина стала не более (?P<target>.+?) м\? Ответ выразите в км/с\."
        ),
    ),
    (
        "root_horizon",
        re.compile(
            r"Наблюдатель находится на высоте h, выраженной в метрах\. Расстояние от наблюдателя до наблюдаемой им линии горизонта, выраженное в километрах, вычисляется по формуле l="
            + _FORMULA
            + r", где R=(?P<radius>.+?) км — радиус Земли\. С какой высоты горизонт виден на расстоянии (?P<target>.+?) километров\? Ответ выразите в (?P<answer_unit>метрах)\."
        ),
    ),
    (
        "root_horizon_km",
        re.compile(
            r"Расстояние(?:\(в км\))? от наблюдателя, находящегося на небольшой высоте h километров над землей, до наблюдаемой им линии горизонта вычисляется по формуле l="
            + _FORMULA
            + r", где R=(?P<radius>.+?)\(км\)— радиус Земли\. С какой высоты горизонт виден на расстоянии (?P<target>.+?) (?:километра|километров)\? Ответ выразите в (?P<answer_unit>километрах)\."
        ),
    ),
    (
        "root_steps",
        re.compile(
            r"Расстояние(?:\(в км\))? от наблюдателя, находящегося на высоте h м над землей,(?: выраженное в километрах,)? до видимой им линии горизонта вычисляется по формуле l="
            + _FORMULA
            + r", где R=(?P<radius>.+?) км — радиус Земли\. Человек, стоящий на пляже, видит горизонт на расстоянии (?P<before>.+?) (?:км|километров)\. К пляжу ведет лестница, каждая ступенька которой имеет высоту (?P<step>.+?) см\. На какое наименьшее количество ступенек нужно подняться человеку, чтобы он увидел горизонт на расстоянии не менее (?P<target>.+?) километров\?"
        ),
    ),
)
