"""The parent square projections establish the required perpendicularity."""


def render(m):
    claim = m.names[1]
    if claim == "B1D":
        return "<p>Проекции B₁D на грани ABB₁A₁ и BB₁C₁C — прямые AB₁ и B₁C. В квадратах AB₁ ⟂ A₁B и B₁C ⟂ BC₁ как диагонали. По теореме о трёх перпендикулярах B₁D перпендикулярна A₁B и BC₁. Эти прямые пересекаются и лежат в плоскости BA₁C₁, поэтому B₁D ⟂ BA₁C₁.</p>"
    if claim == "AC1":
        return "<p>Спроецируем AC₁ на грани BCC₁B₁ и DCC₁D₁. Получим BC₁ и DC₁. Диагонали квадратов перпендикулярны: BC₁ ⟂ B₁C и DC₁ ⟂ D₁C. По теореме о трёх перпендикулярах AC₁ перпендикулярна обеим пересекающимся прямым B₁C и D₁C. Следовательно, AC₁ ⟂ B₁CD₁.</p>"
    return "<p>В квадрате ABB₁A₁ диагонали AB₁ и A₁B перпендикулярны. Кроме того, BC перпендикулярна всей грани ABB₁A₁ и направлению AB₁. Поэтому AB₁ перпендикулярна плоскости A₁BC. Плоскость AB₁D₁ содержит эту прямую, значит, плоскости AB₁D₁ и A₁BC перпендикулярны.</p>"
