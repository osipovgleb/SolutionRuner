def _solve(kind, groups):
    if kind in MEASUREMENTS:
        return measurement(kind, groups)
    if kind in COEFFICIENTS:
        return cut(kind, groups)
    return {
        "transfer": transfer,
        "similar_surface": scale,
        "oblique_rhombus": lambda g: oblique("oblique_rhombus", g),
        "oblique_hex": lambda g: oblique("oblique_hex", g),
        "midline_section": lambda g: section("midline_section", g),
        "median_section": lambda g: section("median_section", g),
        "diagonal_section": diagonal,
    }[kind](groups)


def read(html, source=None):
    raw = text(html, source)
    try:
        for kind, pattern, order in SPECS:
            match = re.fullmatch(pattern, raw)
            if match:
                groups = match.groups()
                return _solve(
                    kind, tuple(groups[i] for i in order) if order else groups
                )
        match = re.fullmatch(
            rf"Дана правильная четырехугольная призма {SQUARE}\s*,?\s*площадь основания которой равна\s+(.+?)\s*, а боковое ребро равно\s+(.+?)\s*\. Найдите объем многогранника, вершинами которого являются точки\s+(.+?)\s*\.",
            raw,
        )
        if match:
            return vertex_volume(match.groups()[:2], vertices(match[3]))
    except UnsupportedCondition as exc:
        raise ContentPlanError(str(exc)) from exc
    raise ContentPlanError("one complete reviewed prism question is required")
